# ---- byte specs (regenerated by the Rust test) -----------------------------------------------
def pattern(n: int, seed: int) -> bytes:
    return bytes((i * 7 + seed) % 251 for i in range(n))


def style_pack(sid: str, flip_last: bool = False) -> bytes:
    rest = sid.encode().ljust(16, b"\0") + b"\0" * 64
    data = b"CSTY" + bytes([1, 0, 96, 0]) + len(rest).to_bytes(4, "little") + zlib.crc32(rest).to_bytes(4, "little") + rest
    if flip_last:
        data = data[:-1] + bytes([data[-1] ^ 1])
    return data


def materialize(spec: dict) -> bytes:
    if "pattern" in spec:
        return pattern(*spec["pattern"])
    if "text" in spec:
        return spec["text"].encode()
    if "json" in spec:
        return json.dumps(spec["json"]).encode()
    if "style_pack" in spec:
        sid, flip = spec["style_pack"]
        return style_pack(sid, bool(flip))
    raise ValueError(spec)


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def crc(b: bytes) -> str:
    return f"{zlib.crc32(b):08x}"


def err(fn):
    try:
        return {"ok": fn()}
    except (ValueError, feed.FeedError) as e:
        return {"error": str(e)}


# ---- manifest ---------------------------------------------------------------------------------
def row(name, kind, size, data_seed=1, **kw):
    d = pattern(size, data_seed)
    return {"name": name, "kind": kind, "size": size, "enc": size + 28, "sha256": sha(d), "crc": crc(d), **kw}


