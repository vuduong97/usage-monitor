def make_pak(count=2, w=4, h=3, frames=2) -> bytes:
    fbytes = (w * h + 1) // 2
    head = b"CLWD" + struct.pack("<HH", 1, count) + bytes(4)
    descs, body = b"", b""
    base = 12 + 72 * count
    for i in range(count):
        frames_off = base + len(body)
        body += bytes([0x12]) * (fbytes * frames)
        holds_off = base + len(body)
        body += struct.pack("<%dH" % frames, *([100] * frames))
        descs += (f"anim{i}".encode().ljust(16, b"\0") + bytes([w, h, 0, 0]) + struct.pack("<4H", frames, 0, max(frames - 1, 0), fbytes)
                  + bytes(32) + struct.pack("<II", frames_off, holds_off) + bytes(4))
    return head + descs + body


