def zip_from(files: dict[str, dict]) -> bytes:
    b = io.BytesIO()
    with zipfile.ZipFile(b, "w", zipfile.ZIP_DEFLATED) as z:
        for n, s in files.items():
            z.writestr(n, materialize(s))
    return b.getvalue()


