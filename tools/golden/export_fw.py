def clip_from_spec(frames: list[dict]) -> bytes:
    out = [b"CLP1", struct.pack("<H", len(frames))]
    for f in frames:
        w, hh = f["w"], f["h"]
        out += [struct.pack("<5H", f["delay"], f["x"], f["y"], w, hh), pattern(w * hh * 3, f["seed"])]
    return b"".join(out)


def frame_summary(f: preview.Frame) -> dict:
    return {"delay_ms": f.delay_ms, "x": f.x, "y": f.y, "w": f.w, "h": f.h, "rgb_sha256": sha(f.rgb)}


def normalized_apng(png: bytes) -> str:
    assert png[:8] == b"\x89PNG\r\n\x1a\n"
    off, parts = 8, []
    while off < len(png):
        (n,) = struct.unpack_from(">I", png, off)
        kind, body = png[off + 4:off + 8], png[off + 8:off + 8 + n]
        assert struct.unpack_from(">I", png, off + 8 + n)[0] == zlib.crc32(kind + body)
        if kind == b"IDAT":
            body = zlib.decompress(body)
        elif kind == b"fdAT":
            body = body[:4] + zlib.decompress(body[4:])
        parts.append(kind + struct.pack(">I", len(body)) + body)
        off += 12 + n
    return sha(b"".join(parts))


